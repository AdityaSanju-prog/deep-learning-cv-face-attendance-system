# 1. Bounding Box Representations & Coordinate Geometry
# =====================================================================

class BoundingBox:
    """
    Standardized bounding box container supporting conversions between
    different computer vision coordinate representations.
    """

    def __init__(self, xmin: float, ymin: float, xmax: float, ymax: float,
                 confidence: float = 1.0, label: str = "face"):
        self.xmin = float(xmin)
        self.ymin = float(ymin)
        self.xmax = float(xmax)
        self.ymax = float(ymax)
        self.confidence = float(confidence)
        self.label = label

    @property
    def width(self) -> float:
        return max(0.0, self.xmax - self.xmin)

    @property
    def height(self) -> float:
        return max(0.0, self.ymax - self.ymin)

    @property
    def area(self) -> float:
        return self.width * self.height

    @property
    def xyxy(self) -> Tuple[int, int, int, int]:
        """Returns integer pixel coordinates (xmin, ymin, xmax, ymax)."""
        return int(round(self.xmin)), int(round(self.ymin)), int(round(self.xmax)), int(round(self.ymax))

    @property
    def xywh(self) -> Tuple[int, int, int, int]:
        """Returns (xmin, ymin, width, height) format."""
        return int(round(self.xmin)), int(round(self.ymin)), int(round(self.width)), int(round(self.height))

    @property
    def center_xy(self) -> Tuple[float, float]:
        """Returns centroid (cx, cy)."""
        return (self.xmin + self.xmax) / 2.0, (self.ymin + self.ymax) / 2.0

    def clip_to_image(self, width: int, height: int) -> 'BoundingBox':
        """Clips box coordinates to valid image dimensions [0, width] and [0, height]."""
        return BoundingBox(
            xmin=max(0.0, min(self.xmin, width - 1)),
            ymin=max(0.0, min(self.ymin, height - 1)),
            xmax=max(0.0, min(self.xmax, width - 1)),
            ymax=max(0.0, min(self.ymax, height - 1)),
            confidence=self.confidence,
            label=self.label
        )


# =====================================================================
# 2. IoU (Intersection over Union) & NMS Implementation
# =====================================================================

def calculate_iou(boxA: BoundingBox, boxB: BoundingBox) -> float:
    """
    Computes Intersection over Union (Jaccard Index) between two bounding boxes:
    IoU = Area(Intersection) / Area(Union)
    """
    xA = max(boxA.xmin, boxB.xmin)
    yA = max(boxA.ymin, boxB.ymin)
    xB = min(boxA.xmax, boxB.xmax)
    yB = min(boxA.ymax, boxB.ymax)

    inter_w = max(0.0, xB - xA)
    inter_h = max(0.0, yB - yA)
    inter_area = inter_w * inter_h

    if inter_area == 0.0:
        return 0.0

    union_area = boxA.area + boxB.area - inter_area
    if union_area <= 0.0:
        return 0.0

    return float(inter_area / union_area)


def non_maximum_suppression(boxes: List[BoundingBox], iou_threshold: float = 0.4) -> List[BoundingBox]:
    """
    Implements greedy Non-Maximum Suppression (NMS) from first principles.
    Eliminates redundant overlapping candidate boxes generated by multi-scale anchors.

    Algorithm:
    1. Sort all boxes in descending order of confidence score.
    2. Pick highest scoring box, add to output list.
    3. Remove any remaining box whose IoU with the picked box exceeds iou_threshold.
    4. Repeat until candidate list is exhausted.
    """
    if not boxes:
        return []

    # Sort descending by confidence
    sorted_boxes = sorted(boxes, key=lambda b: b.confidence, reverse=True)
    selected_boxes: List[BoundingBox] = []

    while sorted_boxes:
        current_best = sorted_boxes.pop(0)
        selected_boxes.append(current_best)

        # Filter out candidates with high IoU overlap
        remaining: List[BoundingBox] = []
        for box in sorted_boxes:
            iou = calculate_iou(current_best, box)
            if iou < iou_threshold:
                remaining.append(box)
        sorted_boxes = remaining

    return selected_boxes


