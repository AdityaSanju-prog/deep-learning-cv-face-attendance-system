# 5. Hybrid Universal Face Detector
# =====================================================================

class UniversalFaceDetector:
    """
    Robust composite face detector:
    Tries Deep SSD detector first (Unit IV: Single-stage DL detector).
    Automatically falls back to Haar Cascade if weights are uninitialized.
    """

    def __init__(self, ssd_conf: float = 0.5):
        self.ssd = SSDResNetFaceDetector(conf_threshold=ssd_conf)
        self.haar = HaarCascadeFaceDetector()

    def detect_faces(self, image_bgr: np.ndarray) -> List[BoundingBox]:
        if self.ssd.is_ready:
            faces = self.ssd.detect(image_bgr)
            if faces:
                return faces
        return self.haar.detect(image_bgr)


