# 3. Single-Stage Deep Detector: OpenCV DNN SSD (ResNet-10 Backbone)
# =====================================================================

class SSDResNetFaceDetector:
    """
    Single-Shot MultiBox Detector (SSD) face detector with a ResNet-10 backbone.
    Characteristics:
    - Single-stage architecture: predicts bounding boxes and class scores directly in one pass
    - Uses default anchors / priors across multiple feature map scales
    - Operates at 300x300 input resolution
    - Ultra-fast CPU inference (<20ms) with high detection recall across orientations.
    """

    def __init__(self, prototxt_path: str = "models/deploy.prototxt",
                 caffemodel_path: str = "models/res10_300x300_ssd_iter_140000.caffemodel",
                 conf_threshold: float = 0.5):
        self.conf_threshold = conf_threshold
        self.is_ready = False

        if os.path.exists(prototxt_path) and os.path.exists(caffemodel_path):
            self.net = cv2.dnn.readNetFromCaffe(prototxt_path, caffemodel_path)
            self.is_ready = True
        else:
            self.net = None

    def detect(self, image_bgr: np.ndarray, nms_threshold: float = 0.4) -> List[BoundingBox]:
        """
        Runs SSD forward pass and applies Non-Maximum Suppression.

        Args:
            image_bgr: Input frame (H, W, C)
            nms_threshold: IoU threshold for overlapping detection suppression

        Returns:
            List of detected BoundingBox instances
        """
        if not self.is_ready or self.net is None:
            return []

        h, w = image_bgr.shape[:2]

        # Preprocessing blob: 300x300, scale 1.0, mean subtraction (104.0, 177.0, 123.0)
        blob = cv2.dnn.blobFromImage(
            image_bgr,
            scalefactor=1.0,
            size=(300, 300),
            mean=(104.0, 177.0, 123.0),
            swapRB=False,
            crop=False
        )

        self.net.setInput(blob)
        detections = self.net.forward()  # Shape: (1, 1, num_detections, 7)

        raw_boxes: List[BoundingBox] = []
        num_preds = detections.shape[2]

        for i in range(num_preds):
            conf = float(detections[0, 0, i, 2])
            if conf > self.conf_threshold:
                # SSD outputs normalized coords [0, 1]
                xmin = detections[0, 0, i, 3] * w
                ymin = detections[0, 0, i, 4] * h
                xmax = detections[0, 0, i, 5] * w
                ymax = detections[0, 0, i, 6] * h

                box = BoundingBox(xmin, ymin, xmax, ymax, confidence=conf, label="face")
                box = box.clip_to_image(w, h)
                if box.width > 15 and box.height > 15:
                    raw_boxes.append(box)

        # Apply Unit IV NMS algorithm
        final_boxes = non_maximum_suppression(raw_boxes, iou_threshold=nms_threshold)
        return final_boxes


