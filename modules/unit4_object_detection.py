# 4. Classical Vision Baseline: Haar Cascade Detector
# =====================================================================

class HaarCascadeFaceDetector:
    """
    Classical object detection baseline implementing Viola-Jones (2001) cascade:
    - Integral image for constant-time rectangular feature computation
    - AdaBoost for weak-to-strong classifier selection
    - Attentional cascade to reject non-face background windows rapidly.
    """

    def __init__(self, scale_factor: float = 1.1, min_neighbors: int = 5):
        self.scale_factor = scale_factor
        self.min_neighbors = min_neighbors
        cascade_path = cv2.data.haarcascades + "haarcascade_frontalface_default.xml"
        self.cascade = cv2.CascadeClassifier(cascade_path)

    def detect(self, image_bgr: np.ndarray) -> List[BoundingBox]:
        gray = cv2.cvtColor(image_bgr, cv2.COLOR_BGR2GRAY)
        rects = self.cascade.detectMultiScale(
            gray,
            scaleFactor=self.scale_factor,
            minNeighbors=self.min_neighbors,
            minSize=(30, 30)
        )
        boxes: List[BoundingBox] = []
        for (x, y, w, h) in rects:
            boxes.append(BoundingBox(x, y, x + w, y + h, confidence=0.85, label="face"))
        return boxes


